// ** VARIABLES: store values and act as the values they store

// **Constants** Constants are variables that cannot be reassigned. They are block-scoped, meaning they are only accessible within the block they are defined in. Constants are declared using the `const` keyword.

// **Variable Naming

// **Camel case**: Camel case is a naming convention where the first word is in lowercase and each subsequent word starts with an uppercase letter. For example: `myVariableName`.

// **Pascal Case**: Pascal case is a naming convention where the first letter of each word is capitalized. For example: `MyVariableName`.

// **Snake case**: Snake case is a naming convention where words are separated by underscores and all letters are in lowercase. For example: `my_variable_name`.