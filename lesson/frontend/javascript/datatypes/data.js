// *** Data Types
// **Primitive Data Types**

// 1. String: A string is a sequence of characters used to represent text. Strings are enclosed in single quotes (' '), double quotes (" "), or backticks (` `). For example: 'Hello, World!', "JavaScript", `Template Literal`.

// 2. Number: A number is a numeric value that can be an integer or a floating-point number. For example: 42, -3.14, 0.5.

// 3. Boolean: A boolean is a data type that can have one of two values: true or false. It is often used for conditional statements and logical operations.

// 4. Undefined: A variable that has been declared but has not been assigned a value is of type undefined. For example: let x; // x is undefined

// 5. Null: Null is a special value that represents the intentional absence of any object value. It is often used to indicate that a variable should not point to any object. For example: let y = null;


// ** reference Data Types **
// arrays, objects, and functions are reference data types. They are used to store collections of data or more complex entities. Unlike primitive data types, reference data types are mutable and can be modified after they are created.